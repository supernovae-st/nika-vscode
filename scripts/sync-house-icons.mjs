// sync-house-icons.mjs — vendor the SuperNovae MASTER icon set.
//
// The site ships a 16-category SUBSET (public/brand/icons · the
// ontology's baked entities). The master library (1986 marks · 24
// grid · stroke 2 · round caps · currentColor) is the studio identity
// pole's; this script vendors the CHROME picks the canvas needs, into
// src/house-icons.generated.ts — checked in, never fetched at build.
//
//   NIKA_ICONS=/path/to/_svg node scripts/sync-house-icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const lib = process.env.NIKA_ICONS ?? '/Users/thibaut/Downloads/_svg';

// name → library path. Every pick is a CHROME verb the canvas speaks;
// the domain marks (verbs · builtins · features) stay with the site
// ontology in icons.generated.ts.
const PICK = {
  // the docks
  plus: 'interface-general/plus-medium',
  minus: 'interface-general/minus-medium',
  fit: 'arrows/expand-45',
  layout: 'layout/layout-grid-1',
  // the run cluster
  play: 'sound-music/play',
  stop: 'sound-music/stop',
  pause: 'sound-music/pause',
  // the lens deck (one mark per lens · the key stays printed)
  lensWaves: 'layout/layers-three',
  lensTimeline: 'filter-settings/filter-timeline',
  lensAudit: 'security/shield-check-2',
  lensDataflow: 'code/api-connection',
  lensCurve: 'edit/bezier-curve',
  lensHeat: 'statistics-charts/analytics',
  lensFollow: 'interface-general/target-1',
  lensFeed: 'interface-general/bars-three',
  // the POLICY chips (v27) · the row is 218 CSS px and already spills at
  // three chips, so a word costs a fact; a mark costs nothing. Six of
  // its glyphs were in no shipped face, and one of them (⤼) carried TWO
  // senses at once — skip AND per-item — which the one-glyph-one-sense
  // law never permitted.
  polRetry: 'arrows/arrow-rotate-clockwise',
  polTimeout: 'time-date/stopwatch',
  polSkip: 'sound-music/skip',
  polParallel: 'arrows/arrow-split-right',
  polPerItem: 'arrows/arrows-repeat-right-left',
  polOuts: 'arrows/arrow-right-square',
  polTools: 'edit/toolbox',
  polTyped: 'security/shield-check-2',
  // the CARD's own surfaces (v27b) · the pill's action cluster, the
  // secret warning, the gate chip, the sim line. Every one of these was
  // an OS-font fallback on a card the user reads every session — and
  // one of them (the key) carries a SECURITY fact.
  secret: 'security/key-1',
  openArtifact: 'folders-files/file-arrow-right-out',
  gate: 'code/branch-simple',
  // the K panel rows (a menu row's mark leads it · Raycast)
  eye: 'accessibility/eye-open',
  pencil: 'edit/pencil-2',
  duplicate: 'interface-general/square-behind-square-1',
  fork: 'code/fork-simple',
  bolt: 'weather/lightning-bolt',
  expandCard: 'arrows/expand-simple',
  chevronDown: 'arrows/chevron-down-small',
  command: 'keyboard/cmd',
  help: 'interface-general/circle-questionmark',
  more: 'interface-general/circle-dots-center-1',
};

if (!existsSync(lib)) {
  console.error(`sync-house-icons: library not found at ${lib} — set NIKA_ICONS`);
  process.exit(1);
}

const rows = [];
const missing = [];
for (const [name, rel] of Object.entries(PICK)) {
  const p = resolve(lib, `${rel}.svg`);
  if (!existsSync(p)) { missing.push(`${name} → ${rel}`); continue; }
  let svg = readFileSync(p, 'utf8')
    .replace(/<!--[\s\S]*?-->\s*/g, '')
    .replace(/\s+xmlns="[^"]*"/, '')
    .replace(/\s+width="[^"]*"/, '')
    .replace(/\s+height="[^"]*"/, '')
    .trim();
  if (!svg.includes('aria-hidden')) { svg = svg.replace('<svg ', '<svg aria-hidden="true" '); }
  rows.push(`  ${name}: '${svg.replace(/'/g, "\\'")}',`);
}
if (missing.length > 0) {
  console.error(`sync-house-icons: missing picks —\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const out = `// house-icons.generated.ts — the SuperNovae MASTER icon set, vendored.
// GENERATED by scripts/sync-house-icons.mjs from the studio identity
// library (24 grid · stroke 2 · round caps · currentColor). The chrome
// picks only — domain marks live in icons.generated.ts (the site
// ontology). Do not edit by hand; rerun the script.
export const HOUSE_ICON = {
${rows.join('\n')}
} as const;
export type HouseIconId = keyof typeof HOUSE_ICON;
`;
writeFileSync(resolve(here, '../src/house-icons.generated.ts'), out);
console.log(`sync-house-icons: ${rows.length} chrome marks vendored → src/house-icons.generated.ts`);
